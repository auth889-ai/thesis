def interface_map():
    fig, ax = canvas("Platform interfaces and lab graduation — what plugs in where", figsize=(17, 9.5))

    box(ax, 0.02, 0.83, 0.96, 0.11,
        "STRUCTURAL TYPING (typing.Protocol): official paper repos are wrapped by ADAPTERS and registered in "
        "common.registry;\nthey never import or inherit DhakaFlow base classes, and upstream source is never vendored.",
        C_PLAT, fs=9, bold=True)

    cols = 5
    x0, w, gap = 0.02, 0.185, 0.012
    for i, m in enumerate(MODULES):
        col, row = i % cols, i // cols
        x = x0 + col * (w + gap)
        y = 0.60 - row * 0.145
        names = EXPORTS[m]
        shown = "\n".join(names[:5]) + ("\n…" if len(names) > 5 else "")
        graduated = m in ("simulation", "control", "safety", "evaluation")
        fc = C_MODEL if graduated else C_PLAT
        label = f"dhakaflow/{m}/" + ("  ✓ Lab 00/01" if graduated else "")
        box(ax, x, y, w, 0.125, f"{label}\n\n{shown}", fc, fs=7.2, bold=graduated)

    box(ax, 0.02, 0.175, 0.47, 0.10,
        "LAB 00 → evaluation/traffic_science.py\n"
        "MFDPoint · CriticalPoint(n*, P*, v*) · distance_to_critical()\n"
        "DIAGNOSTIC / optional feature — not a control target; network-specific",
        C_LAB, fs=8.2, bold=True)
    box(ax, 0.51, 0.175, 0.47, 0.10,
        "LAB 01 → simulation/ · control/ · safety/ · evaluation/\n"
        "SimulationBackend · SignalActuator · SignalAction · TrafficController\n"
        "SafetyConstraints (named profiles, no universal timings) · BenchmarkSpec",
        C_LAB, fs=8.2, bold=True)

    box(ax, 0.02, 0.035, 0.96, 0.105,
        "GRADUATION PATH:   paper reproduction → benchmark → Dhaka adaptation → KEEP decision → adapter → dhakaflow/\n"
        "Frozen results are never edited by platform work; labs cite platform types, the platform never copies lab numbers.",
        C_CTRL, fs=9, bold=True)

    fig.savefig(OUT / "00b_platform_interfaces.png", dpi=170, bbox_inches="tight")
    plt.close(fig)
    print("wrote 00b_platform_interfaces.png")


if __name__ == "__main__":
    master_architecture()
    interface_map()
    print(f"\nfigures in {OUT}")
