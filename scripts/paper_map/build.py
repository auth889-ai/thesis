"""Write docs/PAPER_MAP.md whole, from the summary files (scripts/paper_map/research.py), and the numbering table into
docs/EXPERIMENT_PROTOCOL.md between its markers.

    python scripts/paper_map/build.py            # write
    python scripts/paper_map/build.py --check    # exit 1 if either file differs from what would be written
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import research as R  # noqa: E402

MAP = R.ROOT / "docs/PAPER_MAP.md"
PROTOCOL = R.ROOT / "docs/EXPERIMENT_PROTOCOL.md"
MARK = ("<!-- numbering:start -->", "<!-- numbering:end -->")


def paper_map() -> str:
    L = ["# Paper map", "",
         "One section per research question, generated by `scripts/paper_map/build.py` from the results file named in each section; never edited by hand.",
         "- **Each section has:** the question; data and models; reproduced first; protocol; results; \"The finding\"; \"Why\"; threats to validity; evidence.",
         "- **Every number** is inserted from a results file, and each result names its city and dataset. Where a paper publishes no comparable number, the table says so.", "",
         "## Numbering", "",
         "The questions were renumbered on 2026-10-09 (ML first, then networking and safety). Result folders and code keep their earlier names, because evidence hashes point at them.", "",
         *R.numbering_table(), ""]
    for q in R.all_questions():
        head = f"## {q['id']} — {q['title']}" if q["id"].startswith("RQ") else f"## Supporting measurement — {q['title']}"
        L += [head, "", f"*Group: {q['group']}. City and data: {q['city']}. Summary: `{q['summary']}`.*", "", *q["section"]]
        if L[-1] != "":
            L.append("")
    L += ["## Planned, not run", "", *[f"- **{t}:** {why}" for t, why in R.PLANNED], ""]
    return "\n".join(L)


def protocol(text: str) -> str:
    block = "\n".join([MARK[0], "", "**Numbering used from 2026-10-09** (the questions above keep their frozen wording; this table says where each one now lives):", "",
                       *R.numbering_table(), "", MARK[1]])
    if MARK[0] in text:
        return re.sub(re.escape(MARK[0]) + r".*?" + re.escape(MARK[1]), lambda m: block, text, flags=re.S)
    head, _, rest = text.partition("\n## Rules")
    return head.rstrip() + "\n\n" + block + "\n\n## Rules" + rest


def main(check: bool) -> int:
    want = {MAP: paper_map(), PROTOCOL: protocol(PROTOCOL.read_text())}
    stale = [p for p, t in want.items() if not p.exists() or p.read_text() != t]
    if check:
        for p in stale:
            print("out of date:", p.relative_to(R.ROOT))
        return 1 if stale else 0
    for p in stale:
        p.write_text(want[p])
        print("wrote", p.relative_to(R.ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main("--check" in sys.argv))
